// ─────────────────────────────────────────────────────────────
// 투사 UI 디자인시스템 — 타이포·간격·반경·존·모션
//
// 색은 palette.js, 형태(마크·선·글리프)는 fxlut/fx-core, 여기는 '조판'이다.
// 지금까지 floorgl.js·wallgl.js 가 각자 상수를 들고 있었다(폰트 35종·반경 13종).
// 값은 두 파일이 실제로 쓰던 것에서 뽑아 계단으로 정리한 것이라 대부분 제자리다.
//
// ★ 대지마다 1px 의 실물 크기가 다르다 (PROJECTION-SPEC 6절)
//     벽 2600×1600 = 1.00 mm/px · 지면 러닝 = 0.73 · 지면 농구 = 0.88
//   그래서 '간격'은 mm 로 정의하고 대지에서 환산한다. 같은 72px 가 벽에선 72mm,
//   지면에선 53mm 라 눈에는 다른 간격이었다.
// ─────────────────────────────────────────────────────────────

/** 대지 → 1px 의 실물 mm */
export const MM = { wall: 1.00, run: 0.73, bk: 0.88 };

// ── 간격 ─────────────────────────────────────────────────────
/** 실물 mm 기준 8단 */
export const SP_MM = { s1: 8, s2: 16, s3: 24, s4: 40, s5: 56, s6: 80, s7: 112, s8: 160 };
/** mm → 그 대지의 px */
export const sp = (step, surf = 'wall') => Math.round(SP_MM[step] / MM[surf]);

// ── 타이포 ───────────────────────────────────────────────────
// 두 대지가 쓰던 값(폰트 35종)을 7단으로 클러스터링한 것. 시거리가 달라
// 실물 크기까지 맞추지는 않는다 — 계단만 공유한다.
export const T = { micro: 24, label: 32, body: 40, sub: 52, head: 64, title: 80, display: 120 };
// 수치(OffBit)는 '읽는 글자'가 아니라 링·보드에 맞춰 크기가 정해지는 표시 개체라
// 타이포 계단에서 제외한다. 대지별로 링 지름에 종속.
export const NUM_S = { sm: 90, md: 128, lg: { run: 180, bk: 180, wall: 200 } };

// ── 반경 ─────────────────────────────────────────────────────
export const R = { pill: 999, xl: 80, lg: 64, md: 48, sm: 24, xs: 12 };

// ── 존 밴드 ──────────────────────────────────────────────────
// 대지 높이 비율. 지면 타이틀 176px(6.6%)과 벽 버튼 1226px(76.6%)이 이미 여기
// 맞아 있었다 — 새 규칙이 아니라 잘 맞던 두 값을 나머지 화면에 퍼뜨린 것.
export const ZONE = { title: 0.07, graphic: 0.26, action: 0.78 };
/** 대지 높이 H 에서 그 밴드의 시작 y */
export const zone = (band, H) => Math.round(H * ZONE[band]);

// ── 모션 ─────────────────────────────────────────────────────
// 이미 floorgl/wallgl 에 흩어져 있던 값에 이름만 붙인 것.
export const MO = {
  enter: { dur: 0.8, delay: 0.1 },    // 등장 — eOut
  pop:   { dur: 0.6, delay: 0.95 },   // 배지 — 오버슈트
  float: { dur: 3.6, delay: 1.9 },    // 떠오름 반복
  pulse: { dur: 3.0, delay: 1.9 },    // 글로우 맥동
  wave:  { dur: 2.4, stagger: 0.05 }, // 글자 웨이브
  drift: { dur: 15 },                 // 배경 글로우
};
